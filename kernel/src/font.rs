//! The WovenHat 5x7 bitmap font.
//!
//! Covers every printable ASCII character, 0x20 through 0x7E. The previous
//! glyph table held 14 characters, which meant the desktop could not render
//! its own window title: "WOVENHAT DESKTOP" needs S, K and P, and all three
//! fell through to the placeholder box.
//!
//! Each glyph is seven rows of five pixels. Within a row, bit 4 is the
//! leftmost column and bit 0 the rightmost, which is the convention
//! `Graphics::draw_text` already used. Glyphs advance by `ADVANCE` columns so
//! one blank column separates them.

/// Columns in a glyph cell.
pub const WIDTH: usize = 5;
/// Rows in a glyph cell.
pub const HEIGHT: usize = 7;
/// Horizontal distance between glyph origins, leaving one blank column.
pub const ADVANCE: i32 = 6;
/// Vertical distance between baselines, leaving one blank row.
pub const LINE_HEIGHT: i32 = 9;

/// First character present in the table.
pub const FIRST: char = ' ';
/// Last character present in the table.
pub const LAST: char = '~';

/// Rendered in place of a character outside the table.
pub const REPLACEMENT: [u8; HEIGHT] = [0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F];

