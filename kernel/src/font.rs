/// Whether `character` has a glyph of its own.
pub fn has_glyph(character: char) -> bool {
    (FIRST..=LAST).contains(&character)
}

/// Glyph for `character`, or [`REPLACEMENT`] when it is outside the table.
pub fn glyph(character: char) -> [u8; HEIGHT] {
    // Routed through `has_glyph` so the table's bounds are stated once; a
    // second copy of the range here could drift from it.
    if !has_glyph(character) {
        return REPLACEMENT;
    }
    GLYPHS[character as usize - FIRST as usize]
}

/// Width in pixels of `text` when rendered, excluding the trailing gap.
///
/// Newlines reset the measurement, so the result is the width of the widest
/// line.
pub fn text_width(text: &str) -> usize {
    let mut widest = 0usize;
    let mut current = 0usize;
    for character in text.chars() {
        if character == '\n' {
            widest = widest.max(current);
            current = 0;
            continue;
        }
        current = current.saturating_add(ADVANCE as usize);
    }
    widest = widest.max(current);
    widest.saturating_sub(ADVANCE as usize - WIDTH)
}

/// Number of lines `text` occupies.
pub fn line_count(text: &str) -> usize {
    1usize.saturating_add(text.chars().filter(|character| *character == '\n').count())
}

#[cfg(feature = "stage17-1-test")]
pub fn structural_self_test() -> bool {
    // Every printable character must have its own glyph, and none may collide
    // with the replacement box: that is what the old 14-glyph table failed.
    let mut printable = 0usize;
    let mut character = FIRST;
    loop {
        if !has_glyph(character) {
            return false;
        }
        if character != '~' && glyph(character) == REPLACEMENT {
            return false;
        }
        printable += 1;
        if character == LAST {
            break;
        }
        character = match char::from_u32(character as u32 + 1) {
            Some(next) => next,
            None => return false,
        };
    }
    if printable != 95 {
        return false;
    }

    // Characters outside the table fall back rather than index out of bounds.
    if glyph('\u{7f}') != REPLACEMENT || glyph('\u{a9}') != REPLACEMENT {
        return false;
    }

    // The title the desktop actually draws must be fully renderable. This is
    // the concrete regression the old table caused.
    if !"WOVENHAT DESKTOP".chars().all(has_glyph) {
        return false;
    }
    if "WOVENHAT DESKTOP"
        .chars()
        .any(|character| glyph(character) == REPLACEMENT)
    {
        return false;
    }

    // Distinct characters must not share a bitmap, or text would be ambiguous.
    // Compare the letters and digits, where collisions would matter most.
    let sample = b"ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
    for (index, left) in sample.iter().enumerate() {
        for right in sample.iter().skip(index + 1) {
            if glyph(*left as char) == glyph(*right as char) {
                return false;
            }
        }
    }

    text_width("AB") == 11 && text_width("A\nABC") == 17 && line_count("a\nb\nc") == 3
}
